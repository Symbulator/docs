def run_block(label, book, n, key, settings, results):
    link = f"{B.APP}?lesson={key}&entry={n}"
    lines = [r"\runhead{%s}" % esc(label),
             r"\begin{codebox}", r"\begin{Verbatim}[fontsize=\small]",
             B.entry(book, n), r"\end{Verbatim}", r"\end{codebox}",
             r"\settings{%s}" % esc(settings)]
    for r in results:
        # max width shrinks only an answer too wide for its column (Boulet's).
        lines += [r"\begin{answerbox}",
                  r"\adjustbox{max width=\linewidth}{$\displaystyle %s$}" % r,
                  r"\end{answerbox}"]
    lines.append(r"\applink{%s}" % link)
    return "\n".join(lines)


def problem(p, label):
    out = [r"\begin{problem}{%s}{%s}{%s}{%s}" % (esc(label), esc(p["title"]),
                                                 esc(p["tag"]), esc(p["where"])),
           r"{\itshape %s\par}" % prose(p["question"]),
           r"\vspace{1mm}", figure(p["img"]),
           r"\begin{whybox}\textbf{\sffamily\color{navy}Why it is here.} %s\end{whybox}"
           % esc(p["why"])]
    runs = p["runs"]
    if len(runs) == 1:
        out.append(run_block(*runs[0]))
    else:
        cols = [r"\begin{minipage}[t]{0.485\linewidth}" + "\n" + run_block(*r)
                + "\n" + r"\end{minipage}" for r in runs]
        out.append("\\hfill\n".join(cols))
    out.append(r"\end{problem}")
    return "\n".join(out)


def cover():
    rows = []
    for i, p in enumerate(B.P, 1):
        rows.append(r"\textcolor{accent}{\bfseries %d} & \textbf{%s} & \textcolor{ink2}{\small %s} \\ \hline"
                    % (i, esc(p["title"]), esc(p["tag"])))
    rows.append(r"\textcolor{gold}{\bfseries$\bigstar$} & \textbf{%s} & \textcolor{ink2}{\small %s} \\ \hline"
                % (esc(B.BONUS["title"]), esc(B.BONUS["tag"])))
    return "\n".join([
        r"{\setlength{\fboxsep}{3mm}\colorbox{navy}{\includegraphics[width=20mm]{%s}}}\par"
        % LOGO_REL,
        r"\vspace{5mm}{\sffamily\small\bfseries\color{accent}\addfontfeature{LetterSpace=28}SYMBULATOR 9}\par",
        r"\vspace{3mm}{\sffamily\fontsize{40}{44}\selectfont\bfseries\color{navy}A Baker's Dozen\par}",
        r"\vspace{5mm}{\color{gold}\rule{38mm}{2.2mm}}\par",
        r"\vspace{4mm}{\sffamily\Large\color{ink2}Twelve solved examples from the documentation, and a bonus\par}",
        r"\vspace{7mm}\begin{minipage}{150mm}\large",
        esc("Each of these circuits looks like an afternoon's work by hand. "
            "Symbulator solves each one in a single run, or in two when a switch "
            "splits the problem into intervals. No two of them make the same point. "
            "Every description below is the one in the app's built-in examples, and "
            "every answer was checked against the app on 16 September 2026. The link "
            "under each run opens the entry in the online app."),
        r"\end{minipage}\par",
        r"\vspace{8mm}{\sffamily\arrayrulecolor{rule}\renewcommand{\arraystretch}{1.55}%",
        r"\begin{tabular}{@{}p{9mm}p{72mm}p{85mm}@{}}\hline",
        *rows,
        r"\end{tabular}}",
    ])


def main():
    body = [PREAMBLE, cover()]
    for i, p in enumerate(B.P, 1):
        body.append(problem(p, f"Sample {i} of 12"))
    body.append(problem(B.BONUS, "Bonus"))
    body.append(r"\end{document}" + "\n")
    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n\n".join(body))
    print(f"wrote {OUT}")
    if "--pdf" in sys.argv:
        tmp = tempfile.mkdtemp(prefix="bakers_dozen_tex_")
        for _ in range(2):
            r = subprocess.run(["xelatex", "-interaction=nonstopmode", "-halt-on-error",
                                f"-output-directory={tmp}", "bakers_dozen.tex"],
                               cwd=HERE, capture_output=True, text=True,
                               encoding="utf-8", errors="replace")
        log = io.open(os.path.join(tmp, "bakers_dozen.log"), encoding="utf-8",
                      errors="replace").read()
        pdf = os.path.join(tmp, "bakers_dozen.pdf")
        if r.returncode or not os.path.isfile(pdf):
            print(log[-3000:])
            raise SystemExit("xelatex failed; the log tail is above.")
        target = os.path.join(HERE, "bakers_dozen_latex.pdf")
        shutil.copy2(pdf, target)
        warn = [l for l in log.splitlines() if "Overfull" in l or "Missing character" in l]
        print(f"compiled {target}")
        print(f"{len(warn)} overfull-box or missing-character line(s) in the log")
        for l in warn[:20]:
            print("  ", l)
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
