OUT = os.path.join(HERE, "bakers_dozen.tex")
ASSETS_REL = "../../assets/"          # from this folder to Documentation/assets
LOGO_REL = "../../web/assets/logo.png"
PX_MM = 25.4 / 96                     # the HTML booklet's CSS pixel
MAX_H_MM = 62

TEXT_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
            "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
            "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(s):
    return "".join(TEXT_ESC.get(c, c) for c in s)


def prose(s):
    """Escape text, keeping $...$ maths as maths."""
    parts = re.split(r"(\$[^$]*\$)", s)
    return "".join(p if p.startswith("$") and p.endswith("$") and len(p) > 1
                   else esc(p) for p in parts)


def figure(img):
    if img.startswith("SVG:"):
        return LADDER
    path = os.path.join(B.ASSETS, img)
    w, h = Image.open(path).size
    w_mm, h_mm = w * PX_MM, h * PX_MM
    scale = min(1.0, MAX_H_MM / h_mm)
    return (r"\begin{center}\includegraphics[width=%.1fmm,max width=\linewidth]{%s}"
            r"\end{center}" % (w_mm * scale, ASSETS_REL + img))


