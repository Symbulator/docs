"""A Baker's Dozen as LaTeX: writes bakers_dozen.tex beside this file.

    py paper\\bakers_dozen\\build_dozen_tex.py            write the .tex
    py paper\\bakers_dozen\\build_dozen_tex.py --pdf      and compile it

Roberto, 17 Sep 2026: a LaTeX version of the booklet, for the public
repository. The published PDF (learn.symbulator.com/dozen.pdf) is still the
one build_dozen.py prints through Edge. This writes the same content from
the same data, P and BONUS in build_dozen.py, so the two cannot disagree
about a question, a description or an answer. Edit the data there, never
the generated .tex.

The .tex compiles with XeLaTeX and needs IBM Plex (Sans, Serif and Mono)
installed, DejaVu Sans Mono (it ships with TeX distributions), and the
packages named in its preamble. Plex Serif and Plex Mono have no Greek and
no angle sign, so those characters are mapped with newunicodechar. The
figures are read from Documentation/assets/, relative to the .tex, and
AS7 Problem 19.2's ladder is drawn with circuitikz.
"""
